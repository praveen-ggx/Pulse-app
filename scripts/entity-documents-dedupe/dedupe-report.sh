#!/usr/bin/env bash
# Duplicate vehicle / driver document cleanup — REPORT ONLY.
#
# Reads the database inside a READ ONLY transaction and writes, to OUT_DIR:
#   before_counts.txt      slots / rows / decisions before any change
#   plan.csv               every live row in a duplicated slot + decision + evidence
#   review.csv             rows needing a human decision (never auto-changed)
#   apply.sql              proposed changes for propose_replace rows only; ends in
#                          ROLLBACK — edit to COMMIT only after review and owner GO
#   rollback.sql           exact undo for apply.sql (restores prior status, clears
#                          replaced_by_id) for the same ids
#
# This script never writes to the database. apply.sql / rollback.sql are files
# for review; running them is a separate, explicit, owner-approved step.
#
# Usage:
#   PGPASSWORD=... bash scripts/entity-documents-dedupe/dedupe-report.sh "<postgres url without password>" <out_dir>
# Never print PGPASSWORD. Prod writes are run only by the owner (see CLAUDE.local.md).
set -euo pipefail

DB_URL="${1:?postgres URL (no password) required}"
OUT_DIR="${2:?output directory required}"
HERE="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$OUT_DIR"

run_ro() {
  # $1 = one SELECT that reads the dedupe_* CTEs; runs in a read-only transaction.
  {
    echo "begin transaction read only;"
    cat "$HERE/classify.sql"
    echo "$1;"
    echo "rollback;"
  } | psql "$DB_URL" -X -q -v ON_ERROR_STOP=1 -At -F ','
}

run_ro "
select line from (
  select 0 as k, 'generated_at,' || now()::text as line
  union all select 1, 'slots_with_duplicates,' || (select count(*) from dedupe_slots)
  union all select 2, 'live_rows_in_those_slots,' || (select coalesce(sum(live_rows), 0) from dedupe_slots)
  union all select 3, 'decision,' || decision || ',' || count(*) from dedupe_plan group by decision
  union all select 4, 'by_type,' || entity_type || ',' || doc_type || ',' || decision || ',' || count(*)
    from dedupe_plan group by entity_type, doc_type, decision
) x order by k, line
" > "$OUT_DIR/before_counts.txt"

{
  echo "organization_id,entity_type,entity_id,doc_type,id,status,expiry_date,created_at,current_id,current_status,current_expiry,current_created_at,used_by_trip_document,decision,storage_path"
  run_ro "
select organization_id, entity_type, entity_id, doc_type, id, status, expiry_date, created_at,
       current_id, current_status, current_expiry, current_created_at, used_by_trip_document, decision,
       '\"' || replace(coalesce(storage_path, ''), '\"', '\"\"') || '\"'
from dedupe_plan
order by organization_id, entity_type, entity_id, doc_type, created_at"
} > "$OUT_DIR/plan.csv"

{
  head -1 "$OUT_DIR/plan.csv"
  grep -E ',review_[a-z_]+,' "$OUT_DIR/plan.csv" || true
} > "$OUT_DIR/review.csv"

# One row per proposed change, with everything the reviewed plan assumed:
# (id, expected status, slot org/type/entity/doc_type, replacement id, replacement expiry)
VALUES="$(run_ro "
select string_agg(
  format('  (%L::uuid, %L, %L::uuid, %L, %L::uuid, %L, %L::uuid, %L::date)',
         id, status, organization_id, entity_type, entity_id, doc_type, current_id, current_expiry),
  E',\n' order by id)
from dedupe_plan where decision = 'propose_replace'")"
COUNT="$(run_ro "select count(*) from dedupe_plan where decision = 'propose_replace'")"
# Ambiguous rows are never part of the plan; prove it on the generated output.
LEAK="$(run_ro "select count(*) from dedupe_plan where decision like 'review_%' and id in (select id from dedupe_plan where decision = 'propose_replace')")"
if [ "$LEAK" != "0" ]; then
  echo "ERROR: review rows found in the proposed set — refusing to write apply.sql" >&2
  exit 1
fi

PLAN_TABLE='(
  id uuid primary key,
  expected_status text not null,
  organization_id uuid not null,
  entity_type text not null,
  entity_id uuid not null,
  doc_type text not null,
  replaced_by uuid not null,
  replacement_expiry date not null
)'

if [ "$COUNT" = "0" ]; then
  echo "-- Nothing proposed." > "$OUT_DIR/apply.sql"
  echo "-- Nothing to roll back." > "$OUT_DIR/rollback.sql"
else
  cat > "$OUT_DIR/apply.sql" <<SQL
-- Generated by dedupe-report.sh. REVIEW FIRST. Plans $COUNT rows.
-- Marks older, earlier-expiring copies as replaced by the slot's current copy.
-- Fails with no change unless the database still matches the reviewed plan
-- for EVERY row: the old row has its reviewed status and no replaced_by_id,
-- and its replacement is still live, in the same slot, with the same expiry.
-- Ends in ROLLBACK on purpose; change to COMMIT only with the owner's GO.
begin;

create temp table dedupe_apply $PLAN_TABLE on commit drop;
insert into dedupe_apply (id, expected_status, organization_id, entity_type, entity_id, doc_type, replaced_by, replacement_expiry) values
$VALUES;

do \$\$
declare v_ready int; v_changed int;
begin
  select count(*) into v_ready
    from dedupe_apply p
    join public.entity_documents d on d.id = p.id
    join public.entity_documents r on r.id = p.replaced_by
   where d.status = p.expected_status
     and d.replaced_by_id is null
     and d.organization_id = p.organization_id and d.entity_type = p.entity_type
     and d.entity_id = p.entity_id and d.doc_type = p.doc_type
     and r.status not in ('replaced', 'rejected')
     and r.organization_id = p.organization_id and r.entity_type = p.entity_type
     and r.entity_id = p.entity_id and r.doc_type = p.doc_type
     and r.expiry_date = p.replacement_expiry;
  if v_ready <> $COUNT then
    raise exception 'database differs from the reviewed plan: % of % rows still match — nothing changed', v_ready, $COUNT;
  end if;

  with u as (
    update public.entity_documents d
       set status = 'replaced', replaced_by_id = p.replaced_by, updated_at = now()
      from dedupe_apply p
     where d.id = p.id
       and d.status = p.expected_status
       and d.replaced_by_id is null
    returning d.id
  )
  select count(*) into v_changed from u;
  if v_changed <> $COUNT then
    raise exception 'expected % rows, changed % — aborting', $COUNT, v_changed;
  end if;
  raise notice 'changed % rows', v_changed;
end \$\$;

rollback; -- change to COMMIT only after review + owner GO
SQL

  cat > "$OUT_DIR/rollback.sql" <<SQL
-- Undo for apply.sql: restores the prior status and clears replaced_by_id for
-- exactly the rows apply.sql changed. Fails with no change unless EVERY row is
-- still status 'replaced' pointing at the planned replacement (e.g. if the
-- replacement was deleted since, its link is gone — then undo by hand).
-- Audit rows written by the trigger stay as history.
begin;

create temp table dedupe_undo $PLAN_TABLE on commit drop;
insert into dedupe_undo (id, expected_status, organization_id, entity_type, entity_id, doc_type, replaced_by, replacement_expiry) values
$VALUES;

do \$\$
declare v_ready int; v_changed int;
begin
  select count(*) into v_ready
    from dedupe_undo u
    join public.entity_documents d on d.id = u.id
   where d.status = 'replaced'
     and d.replaced_by_id = u.replaced_by;
  if v_ready <> $COUNT then
    raise exception 'database differs from apply.sql: % of % rows still replaced as planned — nothing changed', v_ready, $COUNT;
  end if;

  with r as (
    update public.entity_documents d
       set status = u.expected_status, replaced_by_id = null, updated_at = now()
      from dedupe_undo u
     where d.id = u.id
       and d.status = 'replaced'
       and d.replaced_by_id = u.replaced_by
    returning d.id
  )
  select count(*) into v_changed from r;
  if v_changed <> $COUNT then
    raise exception 'expected % rows, restored % — aborting', $COUNT, v_changed;
  end if;
  raise notice 'restored % rows', v_changed;
end \$\$;

rollback; -- change to COMMIT only after review + owner GO
SQL
fi

echo "Report written to $OUT_DIR (proposed changes: $COUNT). Nothing was written to the database."
